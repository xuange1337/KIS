import { IsString, Length } from 'class-validator';

export class SearchQueryDto {
  /**
   * Строка поиска.
   *
   * Не короче двух символов: по одной букве совпадает почти всё, и
   * запрос превращается в выгрузку половины базы четырьмя запросами
   * сразу. Верхняя граница отсекает попытку передать в LIKE полотно.
   */
  @IsString()
  @Length(2, 100, {
    message: 'Строка поиска должна быть от 2 до 100 символов',
  })
  q: string;
}
