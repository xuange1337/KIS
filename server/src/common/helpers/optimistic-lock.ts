import { ConflictException } from '@nestjs/common';

/**
 * Проверка версии записи перед сохранением.
 *
 * Два человека открывают одну карточку, правят разные поля и сохраняют:
 * второй молча затирает правку первого, и понять это по данным
 * невозможно — обе операции вернули 200. Версия записи возвращается
 * вместе с ней и присылается обратно при сохранении; если за это время
 * запись изменилась, сохранение отклоняется, а пользователь видит
 * актуальные данные и решает сам.
 *
 * Поле необязательное: клиент, который его не присылает, работает
 * по-прежнему. Так изменение не ломает существующие интеграции.
 */
export function assertVersionMatches(
  current: number,
  expected: number | undefined,
  entityName: string,
): void {
  if (expected === undefined) {
    return;
  }
  if (expected !== current) {
    throw new ConflictException({
      message:
        `${entityName} изменена другим пользователем, пока вы её редактировали. ` +
        'Обновите данные и повторите правку',
      currentVersion: current,
      sentVersion: expected,
    });
  }
}
